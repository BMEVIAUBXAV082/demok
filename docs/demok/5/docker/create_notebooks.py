import json, uuid, os

OUT = os.path.join(os.path.dirname(__file__), "notebooks")
os.makedirs(OUT, exist_ok=True)


def nb(cells):
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.11.0"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def md(source):
    return {"cell_type": "markdown", "id": str(uuid.uuid4())[:8],
            "metadata": {}, "source": source}


def code(source, output=None):
    cell = {"cell_type": "code", "execution_count": None, "id": str(uuid.uuid4())[:8],
            "metadata": {}, "outputs": [], "source": source}
    if output:
        cell["outputs"] = [{"name": "stdout", "output_type": "stream", "text": output}]
    return cell


def save(name, cells):
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(nb(cells), f, ensure_ascii=False, indent=1)
    print(f"  {name}")


